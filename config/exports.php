<?php

declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| Выгрузка базы в Excel из админки
|--------------------------------------------------------------------------
|
| Файлы лежат на диске local (storage/app/private), который на Render
| уведён на постоянный диск: деплой их не стирает. Хранятся последние
| несколько выгрузок — диск на гигабайт, и копить их бесконечно нельзя.
|
| Python-версия выгрузки (python/, перенос площадки на Django) пока
| работает в тени: после каждой выгрузки PHP-версией она выгружает те же
| данные рядом и сверяет книги ячейка в ячейку. Скачивается PHP-файл;
| итог сверки виден в списке. Это финальная проверка переноса на боевых
| данных, без риска для самой выгрузки: сбой Python её не роняет.
|
*/

return [

    // Папка на диске local
    'directory' => 'exports',

    // Сколько последних выгрузок хранить
    'keep' => (int) env('EXPORTS_KEEP', 10),

    // Выгрузка, которая числится идущей дольше этого, считается
    // прерванной: воркер очереди мог умереть посреди работы, и без
    // этого кнопка осталась бы заблокированной навсегда
    'stale_minutes' => 30,

    'python' => [
        'enabled' => (bool) env('EXPORTS_PYTHON_SHADOW', true),
        // В образе Docker — python/.venv, собранный при сборке
        'binary' => env('SAVDEX_PYTHON', base_path('python/.venv/bin/python')),
        'timeout' => 300,
    ],

];
