<?php

declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| Выгрузка базы в Excel из админки
|--------------------------------------------------------------------------
|
| Файлы лежат на диске local (storage/app/private), который на Render
| уведён на постоянный диск: деплой их не стирает. Хранятся последние
| несколько выгрузок — диск на гигабайт, и копить их бесконечно нельзя.
|
| Выгрузку делают обе версии — PHP и Python (python/, перенос площадки
| на Django) — из одного снимка базы, и книги сверяются ячейка в ячейку.
| Скачивается книга основной версии (primary), итог сверки виден в
| списке. С сентября 2026 основная — Python: пять боевых выгрузок подряд
| совпали с PHP. Если Python-выгрузка не удалась, отдаётся PHP-книга.
|
| Откат без деплоя кода: EXPORTS_PRIMARY=php в переменных Render —
| и скачивается снова PHP-книга, а Python уходит в тень.
|
*/

return [

    // Папка на диске local
    'directory' => 'exports',

    // Сколько последних выгрузок хранить
    'keep' => (int) env('EXPORTS_KEEP', 10),

    // Выгрузка, которая числится идущей дольше этого, считается
    // прерванной: воркер очереди мог умереть посреди работы, и без
    // этого кнопка осталась бы заблокированной навсегда
    'stale_minutes' => 30,

    // Чья книга скачивается: python или php
    'primary' => env('EXPORTS_PRIMARY', 'python'),

    'python' => [
        // false — Python не запускается вовсе, только PHP-выгрузка
        'enabled' => (bool) env('EXPORTS_PYTHON_SHADOW', true),
        // В образе Docker — python/.venv, собранный при сборке
        'binary' => env('SAVDEX_PYTHON', base_path('python/.venv/bin/python')),
        'timeout' => 300,
    ],

];
