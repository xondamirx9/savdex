<?php

declare(strict_types=1);

namespace App\Support;

/**
 * Где сейчас работает приложение — у разработчика или у людей.
 *
 * Предохранители разработки (запрет ленивой загрузки связей, строгая
 * проверка массового заполнения) нарочно роняют страницу, чтобы ошибку
 * заметили как можно раньше. На машине разработчика это ровно то, что
 * нужно. На развёрнутом сайте это падение у живого человека.
 *
 * Раньше условием было «не production», и площадка с APP_ENV=staging
 * получала их в полном составе. Вопрос был задан неверно: важно не как
 * называется окружение, а смотрит ли на него кто-то живой. Любое
 * развёрнутое окружение живое, как бы оно ни называлось; местное и
 * тестовое — нет.
 *
 * Список закрытый и короткий намеренно: опечатка в имени окружения
 * теперь означает «это боевой сайт, веди себя осторожно», а не
 * наоборот.
 */
final class Runtime
{
    /** @var list<string> */
    private const DEVELOPER = ['local', 'testing'];

    /** Машина разработчика или прогон тестов. */
    public static function isDeveloperMachine(?string $environment): bool
    {
        return $environment !== null && in_array($environment, self::DEVELOPER, true);
    }

    /**
     * Развёрнутый сайт: production, staging и всё незнакомое.
     *
     * Незнакомое считается развёрнутым осознанно: цена ошибки здесь
     * несимметрична. Лишняя осторожность на машине разработчика стоит
     * неудобства, недостаточная на живом сайте — упавшей страницы
     * у посетителя.
     */
    public static function isDeployed(?string $environment): bool
    {
        return ! self::isDeveloperMachine($environment);
    }
}
