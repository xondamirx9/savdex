<?php

declare(strict_types=1);

namespace App\Exceptions;

use RuntimeException;

/**
 * Попытка вернуть отклонённое объявление на витрину.
 *
 * Отклонение окончательно (§5.7 ТЗ): автор подаёт новую запись.
 * Если объявление можно довести до ума — у модератора для этого
 * есть отдельное решение, «вернуть на исправление».
 *
 * Исключение, а не тихий отказ: молча оставить объявление в прежнем
 * статусе значит показать человеку «сохранено» там, где ничего не
 * сохранилось. Контроллеры проверяют возможность заранее и отвечают
 * понятной фразой; сюда доходит только то, что прошло мимо них.
 */
class RejectedListingStaysDown extends RuntimeException
{
    public function __construct()
    {
        parent::__construct('Отклонённое объявление не возвращается на витрину — нужна новая запись.');
    }
}
