    private const TITLES = [
        'terms' => 'Публичная оферта',
        'payment' => 'Способы оплаты',
        'security' => 'Безопасность платежей',
        'privacy' => 'Политика конфиденциальности',
        'refunds' => 'Политика возвратов',
    ];

    public function show(string $doc): Response
    {
        if (! in_array($doc, self::DOCS, true)) {
            throw new NotFoundHttpException;
        }

        $content = $this->{$doc}();

        /*
         * Оферту и политику ищут по названию компании перед оплатой —
         * страница должна находиться, поэтому от индексации не закрываем.
         */
        app(Seo::class)
            ->title(__("ui.legal.{$doc}_title"))
            ->description($content['intro'])
            ->canonical(url("/{$doc}"));

        return Inertia::render('Legal', [
            'title' => self::TITLES[$doc],
            'intro' => $content['intro'],
            'blocks' => $content['blocks'],
            'updatedAt' => '19.08.2026',
            'draft' => false,
            'siblings' => collect(self::DOCS)->map(fn (string $d) => [
                'href' => "/{$d}",
                'label' => self::TITLES[$d],
                'current' => $d === $doc,
            ])->all(),
        ]);
    }

