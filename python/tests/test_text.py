"""
Склонения.

Значения взяты не из головы, а получены прогоном PHP-функции
App\\Console\\Commands\\CheckPostgres::plural на тех же числах.
Смысл переноса в том, чтобы вывод совпадал; проверка, написанная
по собственному представлению о русском языке, этого не покажет.
"""

from __future__ import annotations

import pytest

from savdex.text import plural

# Число → что ответила PHP-версия
ЭТАЛОН = [
    (0, "0 таблиц"),
    (1, "1 таблица"),
    (2, "2 таблицы"),
    (3, "3 таблицы"),
    (4, "4 таблицы"),
    (5, "5 таблиц"),
    (9, "9 таблиц"),
    (10, "10 таблиц"),
    (11, "11 таблиц"),
    (12, "12 таблиц"),
    (13, "13 таблиц"),
    (14, "14 таблиц"),
    (15, "15 таблиц"),
    (19, "19 таблиц"),
    (20, "20 таблиц"),
    (21, "21 таблица"),
    (22, "22 таблицы"),
    (25, "25 таблиц"),
    (100, "100 таблиц"),
    (101, "101 таблица"),
    (102, "102 таблицы"),
    (105, "105 таблиц"),
    (111, "111 таблиц"),
    (112, "112 таблиц"),
    (114, "114 таблиц"),
    (115, "115 таблиц"),
    (121, "121 таблица"),
    (1000, "1000 таблиц"),
    (1001, "1001 таблица"),
    (1002, "1002 таблицы"),
    (1011, "1011 таблиц"),
    (1021, "1021 таблица"),
]


@pytest.mark.parametrize(("count", "expected"), ЭТАЛОН)
def test_совпадает_с_php(count, expected):
    assert plural(count, "таблица", "таблицы", "таблиц") == expected


def test_подставляются_переданные_слова():
    assert plural(2, "компания", "компании", "компаний") == "2 компании"
