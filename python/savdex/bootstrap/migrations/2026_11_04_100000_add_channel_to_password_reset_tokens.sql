-- Как ушла ссылка сброса пароля: mail — письмом на адрес, sms — после
-- кода из SMS, telegram и whatsapp — в мессенджер.
--
-- Сброс по ссылке из письма доказывает, что человек владеет почтой, и
-- поэтому подтверждает неподтверждённую почту (аккаунт возвращается
-- хозяину адреса). Раньше способ доставки хранился в сессии браузера:
-- открыв ссылку после кода из SMS в другом браузере, сброс выглядел как
-- «по письму» и подтверждал почту, которой человек мог не владеть.
-- Теперь способ — в самой записи токена; почту подтверждает только mail.
-- null — токены, выданные до этой миграции: почту они не подтверждают.

alter table password_reset_tokens add column channel varchar(16);
