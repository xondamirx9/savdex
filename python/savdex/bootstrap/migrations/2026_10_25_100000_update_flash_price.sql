-- Тариф Flash — $10 в месяц вместо $40.
--
-- Цена тарифа живёт в базе (plans), сидер её на рабочей базе не трогает,
-- поэтому меняется здесь. Сумма в сумах считается из долларов по курсу ЦБ
-- и при заказе записывается в счёт (payments.amount) — с ней клиент и
-- уходит в Uzum. price_uzs сбрасывается, чтобы зафиксированная в админке
-- сумма под старую цену не перебила новые $10.

update plans
set price_usd = 10.00, price_uzs = null, updated_at = now()
where code = 'flash';
