-- Цена «от» и диапазон «от – до» в объявлении.
--
-- Поставщик не всегда называет одну цену: она зависит от объёма и
-- комплектации. Раньше оставалось только «цена договорная», а объявления
-- без цены смотрят в 2,4 раза реже.
--
-- price остаётся ценой (у диапазона — нижней границей): на ней работают
-- фильтр и сортировка каталога. price_to — верхняя граница диапазона;
-- price_from — «от»: цена — нижняя, верхней нет.

alter table listings
    add column price_to numeric(16, 2),
    add column price_from boolean not null default false;
