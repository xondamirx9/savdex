export function unitLabel(unit: string | null | undefined): string | null {
    if (!unit) return null;

    const key = ALIASES[unit.trim().toLowerCase().replaceAll('ё', 'е')];

    if (!key) return unit;

    const translated = t(`units.${key}`);

    return translated === `units.${key}` ? unit : translated;
}
